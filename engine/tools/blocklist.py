#!/usr/bin/env python3
"""blocklist.py — engine/port/blocklist/*.txt -> engine/port/BlockerList.inc, the host table of port/Blocker.cpp.

pgl.txt is Peter Lowe's ad and tracking server list (https://pgl.yoyo.org/adservers/, plain host format); --fetch
downloads it again. extra.txt is ours. A host that has a listed parent is dropped (the parent covers it). The table is
one blob of NUL-ended names sorted as bytes plus their offsets: no pointers, so no relocations in webkit.dll.
"""
import os, re, sys, urllib.request

HERE = os.path.join(os.path.dirname(os.path.realpath(__file__)), "..", "port")
SOURCE = "https://pgl.yoyo.org/adservers/serverlist.php?hostformat=nohtml&showintro=0&mimetype=plaintext"

if "--fetch" in sys.argv:
    request = urllib.request.Request(SOURCE, headers={"User-Agent": "curl"})
    data = urllib.request.urlopen(request, timeout=60).read().decode("ascii")
    assert data.count("\n") > 2000, "short list"
    open(os.path.join(HERE, "blocklist", "pgl.txt"), "w").write(data)

hosts = set()
for name in sorted(os.listdir(os.path.join(HERE, "blocklist"))):
    for line in open(os.path.join(HERE, "blocklist", name)):
        line = line.split("#")[0].strip().lower()
        if line:
            assert re.fullmatch(r"[a-z0-9-]+(\.[a-z0-9-]+)+", line), line
            hosts.add(line)


def covered(host):
    parts = host.split(".")
    return any(".".join(parts[i:]) in hosts for i in range(1, len(parts) - 1))


names = sorted((h.encode() for h in hosts if not covered(h)))
offsets, blob = [], b""
for name in names:
    offsets.append(len(blob))
    blob += name + b"\0"
with open(os.path.join(HERE, "BlockerList.inc"), "w") as out:
    out.write("// Generated by engine/tools/blocklist.py from engine/port/blocklist/*.txt: do not edit.\n")
    out.write("static const unsigned blockedHostCount = %d;\n" % len(names))
    out.write("static const char blockedHostNames[] =\n")
    for i in range(0, len(names), 4):
        out.write("    " + " ".join('"%s\\0"' % n.decode() for n in names[i:i + 4]) + "\n")
    out.write(";\nstatic const unsigned blockedHostOffsets[] = {\n")
    for i in range(0, len(offsets), 16):
        out.write("    " + ", ".join(map(str, offsets[i:i + 16])) + ",\n")
    out.write("};\n")
print(len(names), "host,", len(blob), "byte")
