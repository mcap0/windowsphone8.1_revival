static EC_KEY* p256Key(void)
{
    EC_KEY* key = EC_KEY_new_by_curve_name(NID_X9_62_prime256v1);
    BIGNUM* d = BN_bin2bn(p256_priv, sizeof(p256_priv), NULL);
    const EC_GROUP* group = EC_KEY_get0_group(key);
    EC_POINT* point = EC_POINT_new(group);
    if (!d || !point || !EC_KEY_set_private_key(key, d)
        || !EC_POINT_oct2point(group, point, p256_point, sizeof(p256_point), NULL)
        || !EC_KEY_set_public_key(key, point))
        exit(3);
    BN_free(d);
    EC_POINT_free(point);
    return key;
}

int main(int argc, char** argv)
{
    if (argc < 3)
        return 2;
    const char* mode = argv[1];
    long rounds = atol(argv[2]);
    unsigned long done = 0;
    unsigned char out[64];

    if (!strcmp(mode, "p256-verify")) {
        EC_KEY* key = p256Key();
        for (long i = 0; i < rounds; ++i) {
            int s = i & 7;
            if (ECDSA_verify(0, p256_sigs[s].digest, 32, p256_sigs[s].sig, p256_sigs[s].sig_len, key) != 1)
                return 1;
            ++done;
        }
    } else if (!strcmp(mode, "p256-pubkey")) {
        for (long i = 0; i < rounds; ++i) {
            const unsigned char* p = p256_spki;
            EVP_PKEY* pkey = d2i_PUBKEY(NULL, &p, sizeof(p256_spki));
            if (!pkey)
                return 1;
            EVP_PKEY_free(pkey);
            ++done;
        }
    } else if (!strcmp(mode, "p256-keygen")) {
        EC_KEY* key = EC_KEY_new_by_curve_name(NID_X9_62_prime256v1);
        for (long i = 0; i < rounds; ++i) {
            if (!EC_KEY_generate_key(key))
                return 1;
            ++done;
        }
    } else if (!strcmp(mode, "p256-ecdh")) {
        EC_KEY* key = p256Key();
        const EC_GROUP* group = EC_KEY_get0_group(key);
        EC_POINT* peer = EC_POINT_new(group);
        if (!EC_POINT_oct2point(group, peer, p256_peer_point, sizeof(p256_peer_point), NULL))
            return 3;
        for (long i = 0; i < rounds; ++i) {
            if (ECDH_compute_key(out, 32, peer, key, NULL) != 32 || memcmp(out, p256_shared, 32))
                return 1;
            ++done;
        }
    } else if (!strcmp(mode, "p256-sign")) {
        EC_KEY* key = p256Key();
        for (long i = 0; i < rounds; ++i) {
            ECDSA_SIG* sig = ECDSA_do_sign(p256_sigs[i & 7].digest, 32, key);
            if (!sig)
                return 1;
            ECDSA_SIG_free(sig);
            ++done;
        }
    } else if (!strcmp(mode, "x25519-keygen")) {
        unsigned char pub[32], priv[32];
        for (long i = 0; i < rounds; ++i) {
            X25519_keypair(pub, priv);
            ++done;
        }
    } else if (!strcmp(mode, "x25519-ecdh")) {
        unsigned char priv[32];
        memcpy(priv, p256_priv, 32);
        for (long i = 0; i < rounds; ++i) {
            if (!X25519(out, priv, x25519_peer))
                return 1;
            ++done;
        }
    } else if (!strcmp(mode, "rsa2048-verify")) {
        const unsigned char* p = rsa_pub;
        RSA* rsa = d2i_RSAPublicKey(NULL, &p, sizeof(rsa_pub));
        if (!rsa)
            return 3;
        for (long i = 0; i < rounds; ++i) {
            if (RSA_verify(NID_sha256, rsa_digest, sizeof(rsa_digest), rsa_sig, sizeof(rsa_sig), rsa) != 1)
                return 1;
            ++done;
        }
    } else
        return 2;
    printf("%s: %lu\n", mode, done);
    return 0;
}
