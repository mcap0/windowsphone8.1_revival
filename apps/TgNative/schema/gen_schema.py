#!/usr/bin/env python3
"""gen_schema.py — turn the TL schemas (TDLib copies in ref/tdlib) into core/tl_schema.inc.

  apps/TgNative/schema/gen_schema.py            (writes apps/TgNative/core/tl_schema.inc)

Every constructor and function becomes one TlCtorDef row; parameter types are kept as written in the
schema ("flags.3?string", "Vector<Message>", "!X", ...) and interpreted at run time by core/tlobj.cpp.
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
SCHEMES = [os.path.join(ROOT, "ref/tdlib/td/generate/scheme", n) for n in ("mtproto_api.tl", "telegram_api.tl")]
OUT = os.path.join(HERE, "..", "core", "tl_schema.inc")
LINE = re.compile(r"^([a-zA-Z0-9_.]+)#([0-9a-f]{1,8})\s+(.*?)=\s*([^;]+);$")


def main():
    rows, params, seen = [], [], set()
    layer = 0
    # ping is commented out in TDLib's mtproto_api.tl (TDLib uses ping_delay_disconnect); we want both
    extra = ["---functions---", "ping#7abe77ec ping_id:long = Pong;"]
    for path in SCHEMES + [None]:
        is_fn = False
        for raw in (open(path, encoding="utf-8") if path else extra):
            line = raw.split("//")[0].strip()
            if line == "---functions---": is_fn = True; continue
            if line == "---types---": is_fn = False; continue
            m = LINE.match(line)
            if not m: continue
            name, cid, args, result = m.group(1), int(m.group(2), 16), m.group(3), m.group(4).strip()
            if name == "vector" or cid in seen: continue
            seen.add(cid)
            first = len(params)
            for a in args.split():
                if a.startswith("{"): continue          # {X:Type}
                pname, ptype = a.split(":", 1)
                params.append((pname, ptype))
            rows.append((cid, name, result, first, len(params) - first, is_fn))
    vh = open(os.path.join(ROOT, "ref/tdlib/td/telegram/Version.h"), encoding="utf-8").read()
    layer = int(re.search(r"MTPROTO_LAYER\s*=\s*(\d+)", vh).group(1))
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by apps/TgNative/schema/gen_schema.py from ref/tdlib schemas. Do not edit.\n")
        f.write("#define TL_SCHEMA_LAYER %d\n" % layer)
        f.write("static const TlParamDef kTlParams[] = {\n")
        for n, t in params: f.write('{"%s","%s"},\n' % (n, t))
        f.write("};\nstatic const TlCtorDef kTlCtors[] = {\n")
        for cid, name, result, first, n, fn in rows:
            f.write('{0x%08xu,"%s","%s",%d,%d,%d},\n' % (cid, name, result, first, n, 1 if fn else 0))
        f.write("};\n")
    print("layer %d: %d constructors/functions, %d params -> %s" % (layer, len(rows), len(params), os.path.relpath(OUT, ROOT)))


main()
