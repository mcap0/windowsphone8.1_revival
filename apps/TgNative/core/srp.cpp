bool computeSrp(const std::string& password, const std::string& salt1, const std::string& salt2, int g,
                const std::string& p, const std::string& srpB, const uint8_t random256[256],
                std::string& A, std::string& M1)
{
    if (p.size() != 256 || srpB.empty() || srpB.size() > 256 || g < 2) return false;
    std::string ph1 = salted(salted(password, salt1), salt2);
    unsigned char kdf[64];
    if (mbedtls_pkcs5_pbkdf2_hmac_ext(MBEDTLS_MD_SHA512, reinterpret_cast<const unsigned char*>(ph1.data()), ph1.size(),
                                      reinterpret_cast<const unsigned char*>(salt1.data()), salt1.size(), 100000,
                                      sizeof(kdf), kdf) != 0)
        return false;
    std::string x = salted(std::string(reinterpret_cast<char*>(kdf), sizeof(kdf)), salt2);

    Mpi P, G, X, B, a, Av, u, k, v, kv, t, e, S, tmp;
    fromBin(P.v, p);
    mbedtls_mpi_lset(&G.v, g);
    fromBin(X.v, x);
    fromBin(B.v, srpB);
    fromBin(a.v, std::string(reinterpret_cast<const char*>(random256), 256));
    if (mbedtls_mpi_cmp_int(&B.v, 0) <= 0 || mbedtls_mpi_cmp_mpi(&B.v, &P.v) >= 0) return false;

    std::string gPad = toBin(G.v, 256);
    std::string bPad = std::string(256 - srpB.size(), '\0') + srpB;
    if (mbedtls_mpi_exp_mod(&Av.v, &G.v, &a.v, &P.v, 0) != 0) return false;
    A = toBin(Av.v, 256);
    fromBin(u.v, sha(A + bPad));
    fromBin(k.v, sha(p + gPad));
    if (mbedtls_mpi_exp_mod(&v.v, &G.v, &X.v, &P.v, 0) != 0) return false;
    mbedtls_mpi_mul_mpi(&tmp.v, &k.v, &v.v);
    mbedtls_mpi_mod_mpi(&kv.v, &tmp.v, &P.v);
    mbedtls_mpi_sub_mpi(&t.v, &B.v, &kv.v);
    if (mbedtls_mpi_cmp_int(&t.v, 0) < 0) mbedtls_mpi_add_mpi(&t.v, &t.v, &P.v);
    mbedtls_mpi_mul_mpi(&e.v, &u.v, &X.v);
    mbedtls_mpi_add_mpi(&e.v, &e.v, &a.v);
    if (mbedtls_mpi_exp_mod(&S.v, &t.v, &e.v, &P.v, 0) != 0) return false;
    std::string K = sha(toBin(S.v, 256));
    std::string h1 = sha(p), h2 = sha(gPad);
    for (std::size_t i = 0; i < h1.size(); ++i) h1[i] = static_cast<char>(h1[i] ^ h2[i]);
    M1 = sha(h1 + sha(salt1) + sha(salt2) + A + bPad + K);
    return true;
}

std::string strippedToJpeg(const std::string& s)
{
    if (s.size() < 3 || s[0] != 1) return std::string();
    std::string h(reinterpret_cast<const char*>(kStrippedHeader), sizeof(kStrippedHeader));
    std::string out = h.substr(0, 164);
    out += s[1];
    out += h[165];
    out += s[2];
    out += h.substr(167);
    out += s.substr(3);
    out += "\xff\xd9";
    return out;
}

