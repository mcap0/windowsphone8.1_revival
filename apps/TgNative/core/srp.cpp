std::string sha(const std::string& d)
{
    std::vector<uint8_t> h = sha256(reinterpret_cast<const uint8_t*>(d.data()), d.size());
    return std::string(h.begin(), h.end());
}

// TDLib hash_sha256(data, salt) = SHA256(salt | data | salt)
std::string salted(const std::string& data, const std::string& salt) { return sha(salt + data + salt); }

std::string toBin(const mbedtls_mpi& x, std::size_t len)
{
    std::string out(len, '\0');
    mbedtls_mpi_write_binary(&x, reinterpret_cast<unsigned char*>(&out[0]), len);
    return out;
}

void fromBin(mbedtls_mpi& x, const std::string& b)
{
    mbedtls_mpi_read_binary(&x, reinterpret_cast<const unsigned char*>(b.data()), b.size());
}

struct Mpi {
    mbedtls_mpi v;
    Mpi() { mbedtls_mpi_init(&v); }
    ~Mpi() { mbedtls_mpi_free(&v); }
};

