using System.Collections.Generic;
using System.Linq;
using Perle.Cast.Dlna;
using Perle.Extractor;

namespace Perle.Cast
{
    /// <summary>
    /// A video of the cast queue, with the qualities, audio tracks and subtitles that can be chosen
    /// for it.
    /// </summary>
    public sealed class CastItem
    {
        static readonly string[] FormatPreference = { "srt", "vtt", "ttml", "xml", "dfxp" };

        /// <summary>The format the YouTube subtitles are downloaded in.</summary>
        public const string SubtitleFormat = "vtt";

        public StreamInfo Info { get; }
        public string Title { get; }
        public string Uploader { get; }
        public long DurationSeconds { get; }

        /// <summary>
        /// Where the phone player was when the video was sent to the TV, null if it was not playing
        /// it. Used once, instead of the position saved in the history.
        /// </summary>
        public long? HandOffSeconds { get; set; }

        /// <summary>
        /// A lower resolution chosen automatically because the TV could not play a higher one,
        /// null if none. It wins over the resolution wanted by the user for this video.
        /// </summary>
        public int? FallbackHeight { get; set; }

        readonly List<CastStreamCandidate> progressive;
        readonly List<CastStreamCandidate> videoOnly;
        readonly List<CastAudioCandidate> audios;

        /// <summary>The resolutions that can be cast, highest first.</summary>
        public List<int> Qualities { get; }

        /// <summary>The ids of the audio tracks that can be chosen, empty if there is only one.</summary>
        public List<string> AudioTrackIds { get; }

        /// <summary>The subtitles that can be sent to the TV, one per language.</summary>
        public List<SubtitleTrack> Subtitles { get; }

        public CastItem(StreamInfo info)
        {
            Info = info;
            Title = info.Name ?? "";
            Uploader = info.UploaderName ?? "";
            DurationSeconds = info.Duration;
            progressive = info.Formats.Where(f => f.IsVideo).Select(ToCandidate).ToList();
            videoOnly = info.VideoOnly.Select(ToCandidate).ToList();
            audios = info.AudioOnly.Select(ToAudioCandidate).ToList();
            Qualities = CastStreamSelector.Qualities(progressive, videoOnly);
            AudioTrackIds = CastStreamSelector.AudioTracks(audios);
            // YouTube offers every track in every format: one per language, downloaded as SubtitleFormat
            Subtitles = info.Subtitles
                .Where(s => !string.IsNullOrEmpty(s.BaseUrl) && SrtConverter.IsSupported(SubtitleFormat))
                .GroupBy(SubtitleKey).Select(g => g.First()).ToList();
        }

        public bool IsCastable => Choose(null, null) != null;

        /// <param name="height">the wanted resolution, null for automatic</param>
        /// <param name="audioTrackId">the wanted audio track, null for the original one</param>
        public CastChoice Choose(int? height, string audioTrackId) => CastStreamSelector.Choose(progressive, videoOnly, audios, height, audioTrackId);

        /// <returns>what to send to the TV, with the original URLs of the streams</returns>
        public CastMedia Media(CastChoice choice)
        {
            var dash = choice.Dash;
            if (dash != null)
                return new CastMedia
                {
                    Url = dash.Video.Url, Title = Title, Uploader = Uploader, MimeType = TsFormat.Default.MimeType,
                    DurationSeconds = DurationSeconds, ThumbnailUrl = Info.ThumbnailUrl, Dash = dash
                };
            return new CastMedia
            {
                Url = choice.Single.Url, Title = Title, Uploader = Uploader, MimeType = CastStreamSelector.Mp4MimeType,
                DurationSeconds = DurationSeconds, ThumbnailUrl = Info.ThumbnailUrl
            };
        }

        public string AudioTrackName(string trackId) =>
            Info.AudioOnly.FirstOrDefault(a => a.AudioTrackId == trackId)?.AudioTrackName ?? trackId;

        public static string SubtitleName(SubtitleTrack subtitles) =>
            (subtitles.Name ?? subtitles.LanguageTag ?? "?") + (subtitles.IsAutoGenerated && subtitles.Name?.Contains("(") != true ? " (auto)" : "");

        /// <returns>the subtitles matching key (see SubtitleKey), or null</returns>
        public SubtitleTrack FindSubtitles(string key)
        {
            if (key == null) return null;
            var exact = Subtitles.FirstOrDefault(s => SubtitleKey(s) == key);
            if (exact != null) return exact;
            // e.g. "en" wanted and only "en-US" available
            var language = key.Split('|')[0].Split('-')[0];
            return Subtitles.FirstOrDefault(s => LanguageOf(s) == language && !s.IsAutoGenerated)
                ?? Subtitles.FirstOrDefault(s => LanguageOf(s) == language);
        }

        static string LanguageOf(SubtitleTrack s) => (s.LanguageTag ?? "").Split('-')[0];

        /// <summary>Identifies the subtitles of a language across the videos of the queue.</summary>
        public static string SubtitleKey(SubtitleTrack subtitles) => subtitles.LanguageTag + "|" + (subtitles.IsAutoGenerated ? "true" : "false");

        static CastStreamCandidate ToCandidate(StreamFormat f) => new CastStreamCandidate
        {
            Url = f.Url ?? "",
            MimeType = f.MimeType,
            Height = f.Height > 0 ? f.Height : HeightFromLabel(f.QualityLabel),
            IsVideoOnly = f.IsVideo && !(f.Codecs ?? "").Contains("mp4a"),
            IsProgressiveHttp = true, // VISIONOS returns direct URLs
            Codec = FirstCodec(f.Codecs, "avc1"),
            Width = f.Width,
            Bitrate = (int)f.Bitrate,
            InitRange = CastStreamSelector.RangeOf(f.InitStart, f.InitEnd),
            IndexRange = CastStreamSelector.RangeOf(f.IndexStart, f.IndexEnd)
        };

        static CastAudioCandidate ToAudioCandidate(StreamFormat f) => new CastAudioCandidate
        {
            Url = f.Url ?? "",
            MimeType = f.MimeType,
            IsProgressiveHttp = true,
            Codec = f.Codecs,
            Bitrate = (int)f.Bitrate,
            IsOriginal = f.AudioTrackType == null ? (f.AudioTrackId == null || f.IsDefaultAudioTrack) : f.AudioTrackType == "original",
            InitRange = CastStreamSelector.RangeOf(f.InitStart, f.InitEnd),
            IndexRange = CastStreamSelector.RangeOf(f.IndexStart, f.IndexEnd),
            TrackId = f.AudioTrackId
        };

        static int HeightFromLabel(string label)
        {
            if (label == null) return 0;
            int p = label.IndexOf('p');
            return p > 0 && int.TryParse(label.Substring(0, p), out var h) ? h : 0;
        }

        /// <returns>the codec of a muxed stream starting with prefix (e.g. "avc1.42001E" of "avc1.42001E, mp4a.40.2")</returns>
        static string FirstCodec(string codecs, string prefix) =>
            codecs?.Split(',').Select(c => c.Trim()).FirstOrDefault(c => c.StartsWith(prefix)) ?? codecs;
    }
}
