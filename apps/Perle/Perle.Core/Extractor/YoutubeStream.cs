    public sealed class StreamFormat
    {
        public int Itag { get; set; }
        public string Url { get; set; }
        public string MimeType { get; set; }
        public string Codecs { get; set; }
        public bool IsVideo { get; set; }
        public bool IsAudio { get; set; }
        public int Width { get; set; }
        public int Height { get; set; }
        public int Fps { get; set; }
        public string QualityLabel { get; set; }
        public long Bitrate { get; set; }
        public long ContentLength { get; set; } = -1;
        public long ApproxDurationMs { get; set; } = -1;
        /// <summary>Byte ranges of the MP4 initialization data and segment index (DASH).</summary>
        public long InitStart { get; set; } = -1;
        public long InitEnd { get; set; } = -1;
        public long IndexStart { get; set; } = -1;
        public long IndexEnd { get; set; } = -1;
        public string AudioTrackId { get; set; }
        public string AudioTrackName { get; set; }
        public bool IsDefaultAudioTrack { get; set; } = true;
        /// <summary>"original", "dubbed", "descriptive", "secondary" or null (from the xtags of the URL)</summary>
        public string AudioTrackType { get; set; }

        public bool IsH264 => Codecs != null && Codecs.StartsWith("avc1");
        public bool IsAac => Codecs != null && Codecs.StartsWith("mp4a");
    }

    /// <summary>A caption track (port of the subtitles part of YoutubeStreamExtractor).</summary>
    public sealed class SubtitleTrack
    {
        public string BaseUrl { get; set; }
        /// <summary>e.g. "en", "it", "en-US"</summary>
        public string LanguageTag { get; set; }
        public string Name { get; set; }
        public bool IsAutoGenerated { get; set; }

        static readonly Regex FmtParam = new Regex("&fmt=[^&]*");
        static readonly Regex TlangParam = new Regex("&tlang=[^&]*");

        /// <returns>the URL of the subtitles in the given format, e.g. "vtt" or "ttml"</returns>
        public string UrlFor(string format) => TlangParam.Replace(FmtParam.Replace(BaseUrl, ""), "") + "&fmt=" + format;
    }

    public sealed class StreamInfo
    {
        public string VideoId { get; set; }
        public string Url { get; set; }
        public string Name { get; set; }
        public string UploaderName { get; set; }
        public string UploaderUrl { get; set; }
        public long Duration { get; set; }
        public long ViewCount { get; set; }
        public string Description { get; set; }
        public string ThumbnailUrl { get; set; }
        public bool IsLive { get; set; }
        public string HlsUrl { get; set; }
        /// <summary>Muxed (audio + video) progressive streams, rarely returned nowadays.</summary>
        public List<StreamFormat> Formats { get; } = new List<StreamFormat>();
        public List<StreamFormat> AdaptiveFormats { get; } = new List<StreamFormat>();
        public string Cpn { get; set; }
        public List<SubtitleTrack> Subtitles { get; } = new List<SubtitleTrack>();

        public IEnumerable<StreamFormat> VideoOnly => AdaptiveFormats.Where(f => f.IsVideo);
        public IEnumerable<StreamFormat> AudioOnly => AdaptiveFormats.Where(f => f.IsAudio);
    }

    public static class YoutubeStream
    {
        static readonly Regex MimePattern = new Regex(@"^([^;]+);\s*codecs=""([^""]+)""");

        public static async Task<StreamInfo> GetInfoAsync(string videoUrlOrId, CancellationToken ct = default(CancellationToken))
        {
            string videoId = videoUrlOrId.Length == 11 ? videoUrlOrId : StreamUrls.VideoIdFromUrl(videoUrlOrId);
            string cpn = Innertube.GenerateCpn();

            var client = Innertube.VisionOsClient();
            client.VisitorData = await Innertube.GetVisitorDataAsync(client, Innertube.YoutubeiV1GapisUrl, true, ct).ConfigureAwait(false);
            var body = Innertube.PrepareBody(client);
            body["videoId"] = videoId;
            body["cpn"] = cpn;
            body["contentCheckOk"] = true;
            body["racyCheckOk"] = true;

            string url = Innertube.YoutubeiV1GapisUrl + "player?" + Innertube.DisablePrettyPrint
                + "&t=" + Innertube.GenerateTParameter() + "&id=" + videoId;
            var player = await Innertube.PostAsync(url, body, true, ct).ConfigureAwait(false);
            return Parse(player, videoId, cpn);
        }

        /// <summary>The videos YouTube suggests next to a video (watch page sidebar, "next" endpoint, WEB client).</summary>
        public static async Task<List<StreamInfoItem>> GetRelatedAsync(string videoUrlOrId, CancellationToken ct = default(CancellationToken))
        {
            string videoId = videoUrlOrId.Length == 11 ? videoUrlOrId : StreamUrls.VideoIdFromUrl(videoUrlOrId);
            var body = Innertube.PrepareBody(Innertube.WebClient());
            body["videoId"] = videoId;
            var json = await Innertube.PostAsync(Innertube.YoutubeiV1Url + "next?" + Innertube.DisablePrettyPrint, body, false, ct)
                .ConfigureAwait(false);
            var list = new List<StreamInfoItem>();
            var results = json.ObjPath("contents.twoColumnWatchNextResults.secondaryResults.secondaryResults").Arr("results");
            foreach (var r in results.Objects())
            {
                var lockup = r.Obj("lockupViewModel");
                StreamInfoItem item = null;
                try
                {
                    if (lockup.HasValues) item = LockupExtractor.Extract(lockup);
                    else if (r.Obj("compactVideoRenderer").HasValues) item = VideoRendererExtractor.Extract(r.Obj("compactVideoRenderer"));
                }
                catch (ExtractionException) { }  // one odd entry does not hide the others
                if (item != null && item.VideoId != videoId) list.Add(item);
            }
            return list;
        }

        public static StreamInfo Parse(JObject player, string videoId, string cpn)
        {
            var status = player.Obj("playabilityStatus");
            var s = status.Str("status");
            if (s != "OK")
            {
                var reason = status.Str("reason") ?? status.ObjPath("errorScreen.playerErrorMessageRenderer.reason").Text() ?? s;
                throw new ExtractionException("Video non disponibile: " + reason);
            }

            var details = player.Obj("videoDetails");
            var info = new StreamInfo
            {
                VideoId = videoId,
                Url = StreamUrls.FromVideoId(videoId),
                Cpn = cpn,
                Name = details.Str("title"),
                UploaderName = details.Str("author"),
                UploaderUrl = details.Str("channelId") != null ? YoutubeChannel.UrlFromChannelId(details.Str("channelId")) : null,
                Duration = details.Long("lengthSeconds", -1),
                ViewCount = details.Long("viewCount", -1),
                Description = details.Str("shortDescription"),
                ThumbnailUrl = LockupExtractor.BestThumbnail(details.Obj("thumbnail").Arr("thumbnails")),
                IsLive = details.Bool("isLive")
            };

            var sd = player.Obj("streamingData");
            info.HlsUrl = sd.Str("hlsManifestUrl");
            foreach (var f in sd.Arr("formats").Objects()) { var p = ParseFormat(f); if (p != null) info.Formats.Add(p); }
            foreach (var f in sd.Arr("adaptiveFormats").Objects()) { var p = ParseFormat(f); if (p != null) info.AdaptiveFormats.Add(p); }
            foreach (var c in player.ObjPath("captions.playerCaptionsTracklistRenderer").Arr("captionTracks").Objects())
            {
                var baseUrl = c.Str("baseUrl");
                if (baseUrl == null) continue;
                info.Subtitles.Add(new SubtitleTrack
                {
                    BaseUrl = baseUrl,
                    LanguageTag = c.Str("languageCode"),
                    Name = c.Obj("name").Text(),
                    IsAutoGenerated = (c.Str("vssId") ?? "").StartsWith("a.") || c.Str("kind") == "asr"
                });
            }
            return info;
        }

        static StreamFormat ParseFormat(JObject f)
        {
            var url = f.Str("url");
            if (url == null) return null; // ciphered: not expected with VISIONOS
            var m = MimePattern.Match(f.Str("mimeType") ?? "");
            var fmt = new StreamFormat
            {
                Itag = (int)f.Long("itag", 0),
                Url = url,
                MimeType = m.Success ? m.Groups[1].Value : f.Str("mimeType"),
                Codecs = m.Success ? m.Groups[2].Value : null,
                Width = (int)f.Long("width", 0),
                Height = (int)f.Long("height", 0),
                Fps = (int)f.Long("fps", 0),
                QualityLabel = f.Str("qualityLabel"),
                Bitrate = f.Long("bitrate", 0),
                ContentLength = f.Long("contentLength", -1),
                ApproxDurationMs = f.Long("approxDurationMs", -1),
                InitStart = f.Obj("initRange").Long("start", -1),
                InitEnd = f.Obj("initRange").Long("end", -1),
                IndexStart = f.Obj("indexRange").Long("start", -1),
                IndexEnd = f.Obj("indexRange").Long("end", -1)
            };
            fmt.IsVideo = fmt.MimeType != null && fmt.MimeType.StartsWith("video/");
            fmt.IsAudio = fmt.MimeType != null && fmt.MimeType.StartsWith("audio/");
            var track = f.Obj("audioTrack");
            if (track.HasValues)
            {
                fmt.AudioTrackId = track.Str("id");
                fmt.AudioTrackName = track.Str("displayName");
                fmt.IsDefaultAudioTrack = track.Bool("audioIsDefault");
                fmt.AudioTrackType = AudioTrackTypeOf(url);
            }
            return fmt;
        }

        static readonly Regex Acont = new Regex(@"acont(?:=|%3D)([a-z]+)");

        /// <summary>Port of YoutubeParsingHelper.extractAudioTrackType: the "acont" entry of the "xtags" parameter.</summary>
        static string AudioTrackTypeOf(string url)
        {
            var q = url.IndexOf("xtags=");
            if (q < 0) return null;
            var end = url.IndexOf('&', q);
            var xtags = System.Uri.UnescapeDataString(end < 0 ? url.Substring(q + 6) : url.Substring(q + 6, end - q - 6));
            var m = Acont.Match(xtags);
            return m.Success ? m.Groups[1].Value : null;
        }

        /// <summary>
        /// Streams the Lumia can decode in hardware: H.264 video up to <paramref name="maxHeight"/>
        /// and AAC audio (default track first).
        /// </summary>
        public static StreamFormat BestVideo(StreamInfo info, int maxHeight) =>
            info.VideoOnly.Where(f => f.IsH264 && f.Height <= maxHeight)
                .OrderByDescending(f => f.Height).ThenByDescending(f => f.Fps <= 30).ThenByDescending(f => f.Bitrate)
                .FirstOrDefault();

        public static StreamFormat BestAudio(StreamInfo info) =>
            info.AudioOnly.Where(f => f.IsAac)
                .OrderByDescending(f => f.IsDefaultAudioTrack).ThenByDescending(f => f.Bitrate)
                .FirstOrDefault();
    }
